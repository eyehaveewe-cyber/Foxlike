#!/usr/bin/env python3
"""Stamp reproducible duel source identity into exported telemetry."""
from pathlib import Path
import hashlib
import sys
ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'scripts/duel/duel_build.gd'
files = sorted([p for p in (ROOT / 'scripts/duel').glob('*.gd') if p != TARGET] + [ROOT / 'scenes/duel.tscn'])
digest = hashlib.sha256()
for path in files:
    digest.update(str(path.relative_to(ROOT)).encode() + b'\0' + path.read_bytes() + b'\0')
content = 'extends RefCounted\n## Generated by tools/stamp_duel.py; identifies the exact practice implementation.\nconst SOURCE_ID := "phase1-' + digest.hexdigest()[:20] + '"\n'
if '--check' in sys.argv:
    if not TARGET.exists() or TARGET.read_text() != content:
        raise SystemExit('Duel source stamp is stale. Run python tools/stamp_duel.py')
else:
    TARGET.write_text(content)
print(content.splitlines()[-1])
